#!/usr/bin/env python3
# Cozette (assets/cozette.bdf, MIT licence: assets/cozette-LICENSE.txt) as a C
# table for the configurator (danik_hybrid_ports_ui.c): characters 32..126 and
# the few symbols it draws, each its advance, its box and its rows.
# usage: genfont.py > cozette.h
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
WANT = list(range(32, 127)) + [0x2713, 0x2191, 0x2193, 0x2190, 0x2192, 0x2026]

glyphs, cur = {}, None
for line in open(os.path.join(HERE, "..", "..", "assets", "cozette.bdf")):
    w = line.split()
    if not w:
        continue
    if w[0] == "STARTCHAR":
        cur = {"rows": [], "bm": False}
    elif cur is None:
        continue
    elif w[0] == "ENCODING":
        cur["code"] = int(w[1])
    elif w[0] == "DWIDTH":
        cur["dw"] = int(w[1])
    elif w[0] == "BBX":
        cur["bbx"] = tuple(map(int, w[1:]))
    elif w[0] == "BITMAP":
        cur["bm"] = True
    elif w[0] == "ENDCHAR":
        glyphs[cur["code"]] = cur
        cur = None
    elif cur["bm"]:
        cur["rows"].append(w[0])

out = sys.stdout
out.write("// Generated by genfont.py from assets/cozette.bdf (Cozette, MIT licence).\n")
out.write("// Ascent 10, cell 13 high; rows are bits from the left (bit 7 of the first byte).\n\n")
out.write("typedef struct { unsigned code; signed char dw, w, h, x, y; unsigned char rows[13][2]; } Glyph;\n\n")
out.write("static const Glyph cozette[] = {\n")
for code in WANT:
    g = glyphs[code]
    bw, bh, bx, by = g["bbx"]
    rows = []
    for hx in g["rows"]:
        v = int(hx, 16) << (16 - len(hx) * 4)
        rows.append("{0x%02X,0x%02X}" % (v >> 8 & 0xFF, v & 0xFF))
    rows += ["{0,0}"] * (13 - len(rows))
    out.write("  {0x%04X, %d, %d, %d, %d, %d, {%s}},\n" % (code, g["dw"], bw, bh, bx, by, ",".join(rows[:13])))
out.write("};\n")
